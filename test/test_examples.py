def _build(tmp_path: Path, name: str, config: str = "docs/cpdocs.yml", output: str = "build"):
    project = copy_example(tmp_path, name)
    return project, build_current(load_config(project / config), output=project / output)


def _cmake_toolchain() -> None:
    require("cmake", "ninja", "clang++")


def test_python_example_needs_no_compiler(tmp_path: Path) -> None:
    _project, graph = _build(tmp_path, "python-basic")
    assert graph.project == "dice"
    assert stable_entity_id("python", "class", "dice.core.Die") in graph.entities
    assert graph.entities[stable_entity_id("python", "constant", "dice.SIDES")].documentation
    assert not any("_rng" in key for key in graph.entities)
    assert list(graph.variants) == ["default"]


def test_cpp_features_example_documents_every_variant(tmp_path: Path) -> None:
    _cmake_toolchain()
    project, graph = _build(tmp_path, "cpp-features")
    assert graph.project == "demo-solver"
    assert graph.metadata["features"] == {"PROJECT_FEATURES": ["mpi", "cuda"]}
    assert graph.variants["serial"] == {"primary": True, "features": {"PROJECT_FEATURES": []}}
    assert graph.variants["full"]["features"] == {"PROJECT_FEATURES": ["mpi", "cuda"]}

    def variants(kind: str, name: str) -> set[str]:
        return set(graph.entities[stable_entity_id("cpp", kind, name)].variants)

    assert variants("struct", "demo::settings") == {"serial", "mpi", "full"}
    assert variants("struct", "demo::communicator") == {"mpi", "full"}
    assert variants("struct", "demo::device") == {"full"}
    solve = graph.entities[stable_entity_id("cpp", "function", "demo::solve")]
    assert len(solve.signatures) == 3
    by_parameters = {
        signature.compact: (set(variants), signature.documentation)
        for signature, variants in zip(solve.signatures, solve.signature_variants, strict=True)
    }
    assert by_parameters["(const settings &)"][0] == {"serial", "mpi", "full"}
    assert by_parameters["(const settings &, const communicator &)"] == (
        {"mpi", "full"},
        "Solve distributed over the ranks of a communicator.",
    )
    assert by_parameters["(const settings &, const device &)"][0] == {"full"}
    assert not any("detail" in key for key in graph.entities)

    describe = json.loads(
        (
            project / "build" / "cpdocs" / "work" / "current" / "describe" / "manifest.json"
        ).read_text()
    )
    commands = {variant["name"]: variant["commands"][0] for variant in describe["variants"]}
    assert "-DPROJECT_FEATURES=all" in commands["full"]
    assert "-DPROJECT_FEATURES=none" in commands["serial"]


def test_a_different_build_system_gives_the_same_reference(tmp_path: Path) -> None:
    _cmake_toolchain()
    project = copy_example(tmp_path, "cpp-features")
    with_cmake = build_current(load_config(project / "docs" / "cpdocs.yml"), output=project / "a")
    with_minibuild = build_current(
        load_config(project / "docs" / "cpdocs-minibuild.yml"), output=project / "b"
    )
    assert with_cmake.entities == with_minibuild.entities
    assert with_cmake.variants == with_minibuild.variants


